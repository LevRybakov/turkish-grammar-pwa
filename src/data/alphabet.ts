export type LetterKind = 'vowel' | 'consonant';

export interface AlphabetExample {
  tr: string;
  pronunciation: string;
  ru: string;
  audioId: string;
}

export interface TurkishLetter {
  id: string;
  upper: string;
  lower: string;
  nameTr: string;
  audioId: string;
  kind: LetterKind;
  isSpecial: boolean;
  /** Backness for vowels: kalın (твёрдая) / ince (мягкая) */
  vowelBackness?: 'back' | 'front';
  /** Rounding for vowels: düz (неогубленная) / yuvarlak (огубленная) */
  vowelRounding?: 'unrounded' | 'rounded';
  /** Height/width for vowels: geniş (широкая) / dar (узкая) */
  vowelHeight?: 'wide' | 'narrow';
  /** Voiceless Fıstıkçı Şahap consonants */
  isVoicelessFistikci?: boolean;
  ipa: string;
  ruSound: string;
  tip: string;
  trap?: string;
  examples: AlphabetExample[];
}

